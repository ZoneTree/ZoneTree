import type { StyleBuilder, ThemeMode } from '@purestack/ts-style'
import { zoneTreeColors } from './skin'

type LsmStyleContext = ReturnType<typeof createLsmStyleContext>

export function registerLsmArchitectureStyles(root: ReturnType<StyleBuilder['get']>, theme: ThemeMode) {
  const context = createLsmStyleContext(root, theme)

  registerArticleStyles(context)
  registerFigureStyles(context)
  registerPipelineStyles(context)
  registerLookupStyles(context)
  registerPartReuseStyles(context)
  registerResponsiveStyles(context)
}

function createLsmStyleContext(root: ReturnType<StyleBuilder['get']>, theme: ThemeMode) {
  return {
    root,
    colors: zoneTreeColors[theme],
    merge: theme === 'dark' ? '#dfba70' : '#805b1e',
    mergeSurface: theme === 'dark' ? '#30291c' : '#f6eddb',
  }
}

