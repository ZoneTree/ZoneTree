import { registerLsmArchitectureStyles } from './lsm-styles'

export function registerDocsStyles() {
  themes.forEach((theme, palette) => {
    const context = createDocsStyleContext(theme, palette)

    registerDocumentationStyles(context)
    registerLandingLayoutStyles(context)
    registerHeroStyles(context)
    registerCardStyles(context)
    registerQuickstartStyles(context)
    registerBenchmarkStyles(context)
    registerDistributedStyles(context)
    registerCompanionLayoutStyles(context)
    registerAnalyticsStyles(context)
    registerFullTextSearchStyles(context)
    registerClosingStyles(context)
    registerLightThemeStyles(context)
    registerResponsiveStyles(context)
    registerHeroMotionStyles(context.root, theme)
    registerLsmArchitectureStyles(context.root, theme)
  })
}

type DocsStyleContext = ReturnType<typeof createDocsStyleContext>

function createDocsStyleContext(theme: ThemeMode, palette: ThemePalette) {
  const root = styleBuilder.get(theme)
  const neutral = palette.semanticTone.neutral
  const c = theme === 'dark' ? zoneTreeColors.dark : zoneTreeColors.light
  const ink = neutral.text.default
  const muted = neutral.text.subtle
  const edge = neutral.border.subtle
  const surface = neutral.surface.rest.bgcolor
  const accent = c.accentInk
  const orange = theme === 'dark' ? '#ffab61' : '#a9470b'
  const searchAccent = theme === 'dark' ? '#83d5eb' : '#21697a'

  return { root, theme, neutral, c, ink, muted, edge, surface, accent, orange, searchAccent }
}

